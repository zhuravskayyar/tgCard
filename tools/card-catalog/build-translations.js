// Generates client/src/locales/cardTranslations.ts and fails if any card or collection name has no translation.
const fs = require("fs");
const path = require("path");
const cards = require("./catalog-cards.js");
const translations = require("./catalog-translations.js");
const data = fs.readFileSync(path.join(__dirname, "../../server/src/collections/catalogData.generated.ts"), "utf8");
const collectionNames = [...data.matchAll(/"displayName": "([^"]+)",\s*"bonus"/g)].map((match) => match[1]);
const core = fs.readFileSync(path.join(__dirname, "../../client/src/locales/coreTranslations.ts"), "utf8");

const rows = [];
const problems = [];
for (const [key, [name, , description]] of Object.entries(cards)) {
  const row = translations[key];
  if (!row || row.length !== 6 || row.some((text) => !text)) { problems.push("card " + key); continue; }
  rows.push([name, row[0], row[2], row[4]], [description, row[1], row[3], row[5]]);
}
const collectionRows = translations.__collections;
for (const name of collectionNames) {
  if (!collectionRows.some((row) => row[0] === name) && !core.includes(`["${name}"`)) problems.push("collection " + name);
}
rows.push(...collectionRows);
if (problems.length) { console.error("Missing:\n" + problems.join("\n")); process.exit(1); }
const body = rows.map((row) => "  " + JSON.stringify(row) + ",").join("\n");
fs.writeFileSync(path.join(__dirname, "../../client/src/locales/cardTranslations.ts"), `// Generated by tools/card-catalog/build-translations.js. Each row: Ukrainian, English, German, Russian.\nexport const CARD_TRANSLATIONS: ReadonlyArray<readonly [string, string, string, string]> = [\n${body}\n];\n`, "utf8");
console.log(`ok: ${Object.keys(cards).length} cards, ${collectionNames.length} collections checked, ${rows.length} rows`);
